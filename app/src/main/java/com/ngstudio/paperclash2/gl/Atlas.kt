package com.ngstudio.paperclash2.gl

import android.content.Context
import android.graphics.Bitmap
import android.graphics.BitmapFactory
import android.graphics.Canvas
import android.graphics.Color
import android.graphics.Paint
import android.graphics.RectF
import android.graphics.Typeface
import android.opengl.GLES30
import android.opengl.GLUtils
import android.util.Log
import org.json.JSONObject

/** A sprite's UV rectangle in the atlas and its suggested world size (longest side, in cells). */
class Sprite(val u0: Float, val v0: Float, val u1: Float, val v1: Float, val aspect: Float, val cells: Float)

/**
 * Shared textures: the sprite atlas generated by tools/art (props, pickups, scissors, shadows,
 * confetti), the tileable paper grain, and a 1×1 white texture for untextured quads.
 */
class Atlas(private val context: Context) {
    var texture = 0
        private set
    var grain = 0
        private set
    var white = 0
        private set
    private val sprites = HashMap<String, Sprite>()
    private val fallback = Sprite(0f, 0f, 1f, 1f, 1f, 1f)

    fun load() {
        white = Gl.genTexture()
        GLES30.glBindTexture(GLES30.GL_TEXTURE_2D, white)
        Gl.params(linear = true, repeat = false)
        val px = Bitmap.createBitmap(4, 4, Bitmap.Config.ARGB_8888)
        px.eraseColor(Color.WHITE)
        GLUtils.texImage2D(GLES30.GL_TEXTURE_2D, 0, px, 0)
        px.recycle()

        grain = try {
            context.assets.open("textures/paper_grain.png").use { s ->
                val bmp = BitmapFactory.decodeStream(s)
                val t = Gl.bitmapTexture(bmp, repeat = true, mip = true)
                bmp.recycle()
                t
            }
        } catch (e: Exception) {
            Log.w("PaperGL", "paper_grain missing: ${e.message}")
            white
        }

        try {
            val json = context.assets.open("textures/atlas.json").bufferedReader().use { it.readText() }
            val root = JSONObject(json)
            val w = root.optInt("width", 2048).toFloat()
            val h = root.optInt("height", 2048).toFloat()
            val list = root.getJSONObject("sprites")
            for (key in list.keys()) {
                val o = list.getJSONObject(key)
                val x = o.getInt("x").toFloat()
                val y = o.getInt("y").toFloat()
                val sw = o.getInt("w").toFloat()
                val sh = o.getInt("h").toFloat()
                // Half-texel inset avoids bleeding from neighbours under linear filtering.
                sprites[key] = Sprite(
                    (x + 0.5f) / w, (y + 0.5f) / h, (x + sw - 0.5f) / w, (y + sh - 0.5f) / h,
                    sw / sh, o.optDouble("cells", 2.0).toFloat(),
                )
            }
            val opts = BitmapFactory.Options().apply { inScaled = false }
            val bmp = context.assets.open("textures/atlas.png").use { BitmapFactory.decodeStream(it, null, opts) }
            texture = if (bmp != null) Gl.bitmapTexture(bmp, repeat = false, mip = true).also { bmp.recycle() } else white
        } catch (e: Exception) {
            Log.w("PaperGL", "atlas missing: ${e.message}")
            texture = white
        }
    }

    fun has(name: String) = sprites.containsKey(name)

    fun sprite(name: String): Sprite = sprites[name] ?: fallback

    fun release() {
        if (texture != white) Gl.deleteTexture(texture)
        if (grain != white) Gl.deleteTexture(grain)
        Gl.deleteTexture(white)
        texture = 0
        grain = 0
        white = 0
    }
}

/**
 * Paper price-tag name labels: one slot per plane in a texture drawn with Android's Canvas, redrawn
 * only when the shown percentage changes.
 */
class Labels(private val context: Context) {
    var texture = 0
        private set
    private val bmp = Bitmap.createBitmap(SLOT_W * COLS, SLOT_H * ROWS, Bitmap.Config.ARGB_8888)
    private val slot = Bitmap.createBitmap(SLOT_W, SLOT_H, Bitmap.Config.ARGB_8888)
    private val canvas = Canvas(slot)
    private val shown = IntArray(COLS * ROWS) { -1 }
    private val names = arrayOfNulls<String>(COLS * ROWS)
    private val font: Typeface = try {
        Typeface.createFromAsset(context.assets, "fonts/Fredoka-700.ttf")
    } catch (_: Exception) {
        Typeface.DEFAULT_BOLD
    }
    private val paint = Paint(Paint.ANTI_ALIAS_FLAG)
    private val rect = RectF()

    fun create() {
        texture = Gl.genTexture()
        GLES30.glBindTexture(GLES30.GL_TEXTURE_2D, texture)
        Gl.params(linear = true, repeat = false)
        bmp.eraseColor(0)
        GLUtils.texImage2D(GLES30.GL_TEXTURE_2D, 0, bmp, 0)
        shown.fill(-1)
    }

    /** Makes sure slot [i] shows [name] with [percent] (tenths); uploads only on change. */
    fun ensure(i: Int, name: String, percent10: Int, color: Int, isHuman: Boolean) {
        if (shown[i] == percent10 && names[i] == name) return
        shown[i] = percent10
        names[i] = name
        slot.eraseColor(0)
        val w = SLOT_W.toFloat()
        val h = SLOT_H.toFloat()
        // tag body with a soft shadow
        paint.style = Paint.Style.FILL
        paint.color = Color.argb(70, 20, 20, 50)
        rect.set(6f, 10f, w - 4f, h - 4f)
        canvas.drawRoundRect(rect, 18f, 18f, paint)
        paint.color = if (isHuman) Color.rgb(255, 253, 248) else Color.rgb(255, 250, 240)
        rect.set(4f, 4f, w - 8f, h - 10f)
        canvas.drawRoundRect(rect, 18f, 18f, paint)
        // coloured stripe and punched hole
        paint.color = color
        rect.set(4f, 4f, 30f, h - 10f)
        canvas.drawRoundRect(rect, 14f, 14f, paint)
        canvas.drawRect(20f, 4f, 30f, h - 10f, paint)
        paint.color = Color.rgb(255, 253, 248)
        canvas.drawCircle(17f, (h - 6f) / 2f, 5f, paint)
        // text
        paint.typeface = font
        paint.textSize = 30f
        paint.color = Color.rgb(31, 42, 74)
        val pct = "${percent10 / 10}.${percent10 % 10}%"
        val pctW = paint.measureText(pct)
        var label = name
        val maxNameW = w - 52f - pctW - 14f
        if (paint.measureText(label) > maxNameW) {
            while (label.length > 3 && paint.measureText("$label...") > maxNameW) label = label.dropLast(1)
            label = label.trimEnd() + "..."
        }
        canvas.drawText(label, 40f, h / 2f + 4f, paint)
        paint.color = darken(color)
        canvas.drawText(pct, w - 16f - pctW, h / 2f + 4f, paint)
        val cx = (i % COLS) * SLOT_W
        val cy = (i / COLS) * SLOT_H
        GLES30.glBindTexture(GLES30.GL_TEXTURE_2D, texture)
        GLUtils.texSubImage2D(GLES30.GL_TEXTURE_2D, 0, cx, cy, slot)
    }

    private fun darken(c: Int): Int = Color.rgb((Color.red(c) * 0.72f).toInt(), (Color.green(c) * 0.72f).toInt(), (Color.blue(c) * 0.72f).toInt())

    fun u0(i: Int) = ((i % COLS) * SLOT_W + 0.5f) / (SLOT_W * COLS)
    fun v0(i: Int) = ((i / COLS) * SLOT_H + 0.5f) / (SLOT_H * ROWS)
    fun u1(i: Int) = ((i % COLS) * SLOT_W + SLOT_W - 0.5f) / (SLOT_W * COLS)
    fun v1(i: Int) = ((i / COLS) * SLOT_H + SLOT_H - 0.5f) / (SLOT_H * ROWS)

    fun invalidate() = shown.fill(-1)

    fun release() {
        Gl.deleteTexture(texture)
        texture = 0
    }

    companion object {
        const val SLOT_W = 320
        const val SLOT_H = 64
        const val COLS = 4
        const val ROWS = 4
        const val ASPECT = SLOT_W / SLOT_H.toFloat()
    }
}
