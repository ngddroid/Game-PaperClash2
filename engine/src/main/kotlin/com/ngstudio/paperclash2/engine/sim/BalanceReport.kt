package com.ngstudio.paperclash2.engine.sim

import com.ngstudio.paperclash2.engine.ai.BotProfile
import com.ngstudio.paperclash2.engine.level.LevelGenerator
import com.ngstudio.paperclash2.engine.level.Worlds
import java.io.File
import java.util.Locale
import java.util.stream.Collectors
import java.util.stream.IntStream
import kotlin.math.roundToInt

/** Aggregated simulation numbers for one level and one autopilot skill. */
class LevelStats(
    val level: Int, val wins: Int, val runs: Int, val medianWinTime: Float, val avgStars: Float, val popped: Int,
    val avgPercent: Float = 0f,
    val causes: String = "",
) {
    val winRate: Float get() = wins.toFloat() / runs
}

object Balance {
    fun stats(level: Int, pilot: BotProfile, seeds: Int, bank: Boolean = true): LevelStats {
        val spec = LevelGenerator.spec(level)
        val arena = LevelGenerator.buildArena(spec)
        val outcomes = IntStream.range(0, seeds).parallel().mapToObj { i ->
            Simulator.run(spec, arena, pilot, 0x51D0L * 31 + level * 1009L + i * 7919L, bank)
        }.collect(Collectors.toList())
        val wins = outcomes.filter { it.won }
        val times = wins.map { it.time }.sorted()
        val median = if (times.isEmpty()) 0f else times[times.size / 2]
        val stars = if (outcomes.isEmpty()) 0f else outcomes.sumOf { it.stars } / outcomes.size.toFloat()
        val pct = if (outcomes.isEmpty()) 0f else outcomes.sumOf { it.percent.toDouble() }.toFloat() / outcomes.size
        val hunted = outcomes.count { it.popped && it.hunted }
        val accident = outcomes.count { it.popped && !it.hunted && it.cause == com.ngstudio.paperclash2.engine.world.Cause.SNIPPED }
        val surrounded = outcomes.count { it.popped && it.cause == com.ngstudio.paperclash2.engine.world.Cause.SURROUNDED }
        val hazard = outcomes.count { it.popped && it.cause == com.ngstudio.paperclash2.engine.world.Cause.HAZARD }
        val timeouts = outcomes.count { !it.won && !it.popped }
        return LevelStats(level, wins.size, outcomes.size, median, stars, outcomes.count { it.popped }, pct,
            "hunt $hunted acc $accident sur $surrounded haz $hazard time $timeouts")
    }
}

/**
 * Command-line entry (`./gradlew :engine:balanceReport`): simulates levels 1–10 with many seeds
 * for each skill, then every 10th level with fewer seeds, and writes a markdown report.
 */
fun main(args: Array<String>) {
    if (args.getOrNull(0) == "diag") {
        val seeds = args.getOrElse(1) { "16" }.toInt()
        for (lv in args.drop(2).map { it.toInt() }) {
            val spec = LevelGenerator.spec(lv)
            val nov = Balance.stats(lv, BotProfile.NOVICE, seeds, bank = false)
            val exp = Balance.stats(lv, BotProfile.EXPERT, seeds, bank = false)
            println(String.format(Locale.US, "L%-5d d=%.2f %-9s %-9s riv=%2d goal=%-24s | nov %3.0f%% [%s] | exp %3.0f%% [%s] st %.1f",
                lv, spec.difficulty, spec.mode.title, spec.shapeId, spec.rivals.size, spec.goal.summary(),
                nov.winRate * 100, nov.causes, exp.winRate * 100, exp.causes, exp.avgStars))
        }
        return
    }
    val out = File(args.getOrElse(0) { "BALANCE_REPORT.md" })
    val seeds = args.getOrElse(1) { "200" }.toInt()
    val sampleSeeds = args.getOrElse(2) { "12" }.toInt()
    val sb = StringBuilder()
    sb.append("# Paper Clash 2 — Balance report\n\n")
    sb.append("Generated by `./gradlew :engine:balanceReport` (generator v${LevelGenerator.VERSION}, claim factor ${LevelGenerator.claimFactor}).\n\n")
    sb.append("An autopilot sits in the player's seat and banks the win at the first star. ")
    sb.append("Novice / Casual / Expert differ in reaction time, loop size, caution and steering noise.\n\n")
    sb.append("## Levels 1–10 ($seeds seeds each)\n\n")
    sb.append("| Level | Shape | Mode | Rivals | Novice win | Casual win | Expert win | Novice median win time | Timer |\n")
    sb.append("|---|---|---|---|---|---|---|---|---|\n")
    val t0 = System.currentTimeMillis()
    for (n in 1..10) {
        val spec = LevelGenerator.spec(n)
        val novice = Balance.stats(n, BotProfile.NOVICE, seeds)
        val casual = Balance.stats(n, BotProfile.CASUAL, seeds)
        val expert = Balance.stats(n, BotProfile.EXPERT, seeds)
        sb.append(String.format(Locale.US, "| %d | %s | %s | %d | %.0f%% | %.0f%% | %.0f%% | %.0f s | %.0f s |\n",
            n, spec.shapeId, spec.mode.title, spec.rivals.size, novice.winRate * 100, casual.winRate * 100,
            expert.winRate * 100, novice.medianWinTime, spec.timeLimit))
        println("level $n: novice ${(novice.winRate * 100).roundToInt()}% casual ${(casual.winRate * 100).roundToInt()}% expert ${(expert.winRate * 100).roundToInt()}%")
    }
    sb.append("\n## Sampled levels 20–5000 ($sampleSeeds seeds each, every 10th level shown per 250)\n\n")
    sb.append("| Level | World | Difficulty | Shape | Mode | Rivals | Goal | Novice win | Expert win |\n")
    sb.append("|---|---|---|---|---|---|---|---|---|\n")
    var expertSum = 0f
    var expertCount = 0
    var noviceSum = 0f
    var level = 20
    while (level <= Worlds.TOTAL_LEVELS) {
        val spec = LevelGenerator.spec(level)
        val novice = Balance.stats(level, BotProfile.NOVICE, sampleSeeds)
        val expert = Balance.stats(level, BotProfile.EXPERT, sampleSeeds)
        expertSum += expert.winRate
        noviceSum += novice.winRate
        expertCount++
        if (level % 250 == 0 || level % 250 == 120 || level <= 100) {
            sb.append(String.format(Locale.US, "| %d | %d | %.2f | %s | %s | %d | %s | %.0f%% | %.0f%% |\n",
                level, spec.world, spec.difficulty, spec.shapeId, spec.mode.title, spec.rivals.size,
                spec.goal.summary(), novice.winRate * 100, expert.winRate * 100))
        }
        if (level % 500 == 0) println("sampled up to $level")
        level += 10
    }
    sb.append(String.format(Locale.US, "\nAverage over %d sampled levels: Expert %.0f%%, Novice %.0f%%.\n",
        expertCount, expertSum / expertCount * 100, noviceSum / expertCount * 100))
    sb.append(String.format(Locale.US, "\nRun time: %.1f min.\n", (System.currentTimeMillis() - t0) / 60000f))
    out.parentFile?.mkdirs()
    out.writeText(sb.toString())
    println("wrote ${out.absolutePath}")
}
